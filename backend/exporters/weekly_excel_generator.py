"""
Master Institutional Weekly Excel Workbook Generator
Builds exactly TWO department sheets (CSE - Cyber Security, CSE - IoT).
Consumes ONLY the canonical dataset generated by weekly_report_service.
Does NOT query the database.
"""
import os
import openpyxl
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
from openpyxl.drawing.image import Image
from openpyxl.utils import coordinate_to_tuple
from typing import Dict, Any

from backend.config.report_config import BATCH_CONFIG, get_coordinator_for_department


def build_weekly_performance_excel(data: Dict[str, Any], filepath: str) -> str:
    """
    Generates the simplified 2-sheet submission-ready Excel workbook.
    """
    wb = openpyxl.Workbook()
    wb.active

    raw_date = None
    for cand in [data.get("session_date"), data.get("contest_date"), data.get("report_date"), (data.get("current_session") or {}).get("session_date")]:
        if cand:
            c_str = str(cand).strip()
            if not c_str.isdigit() and len(c_str) >= 8 and ('.' in c_str or '-' in c_str or '/' in c_str):
                raw_date = c_str
                break
    if not raw_date:
        raw_date = "11.10.2026"
    report_date = raw_date.replace("-", ".").replace("/", ".")
    
    # Palette: Professional Institutional Restrained Navy/Slate
    navy_fill = PatternFill(start_color="002060", end_color="002060", fill_type="solid")
    brand_fill = PatternFill(start_color="0070C0", end_color="0070C0", fill_type="solid")
    sub_header_fill = PatternFill(start_color="D9D9D9", end_color="D9D9D9", fill_type="solid")
    section_fill = PatternFill(start_color="F2F2F2", end_color="F2F2F2", fill_type="solid")

    font_title = Font(name="Times New Roman", size=14, bold=True, color="FFFFFF")
    font_subtitle = Font(name="Times New Roman", size=11, italic=True, color="FFFFFF")
    font_tbl_head = Font(name="Times New Roman", size=11, bold=True, color="000000")
    font_bold = Font(name="Times New Roman", size=11, bold=True)
    font_regular = Font(name="Times New Roman", size=11)

    thin_border_side = Side(style='thin', color='000000')
    grid_border = Border(left=thin_border_side, right=thin_border_side, top=thin_border_side, bottom=thin_border_side)
    thick_border_side = Side(style='medium', color='000000')
    outer_border = Border(left=thick_border_side, right=thick_border_side, top=thick_border_side, bottom=thick_border_side)

    align_center = Alignment(horizontal='center', vertical='center', wrap_text=False)
    align_left = Alignment(horizontal='left', vertical='center', wrap_text=False)

    def setup_page_layout(ws):
        # 16. Reset worksheet print settings
        ws.sheet_properties.pageSetUpPr.fitToPage = True
        
        # 6. Landscape orientation
        ws.page_setup.orientation = ws.ORIENTATION_LANDSCAPE
        ws.page_setup.paperSize = ws.PAPERSIZE_A4
        
        # 7. Fit to 1 page wide by 1 page tall
        ws.page_setup.fitToPage = True
        ws.page_setup.fitToWidth = 1
        ws.page_setup.fitToHeight = 1
        
        # 8. Set appropriate page margins
        ws.page_margins.left = 0.25
        ws.page_margins.right = 0.25
        ws.page_margins.top = 0.30
        ws.page_margins.bottom = 0.30
        
        # 17. Remove existing page breaks
        ws.row_breaks = []
        ws.col_breaks = []
        
        # 18. Clear print titles if any
        ws.print_title_rows = None
        ws.print_title_cols = None

    dept_summaries = data.get("department_summaries", [])
    
    # We strictly enforce only two departments as per Absolute Rule 4.
    allowed_depts = [
        {"code": "CSE(CS)", "sheet_name": "Cyber Security", "full_name": "Department of Computer Science and Engineering (Cyber Security)"},
        {"code": "CSE(IOT)", "sheet_name": "Internet of Things", "full_name": "Department of Computer Science and Engineering (IoT)"}
    ]

    for dept_spec in allowed_depts:
        ws = wb.create_sheet(title=dept_spec["sheet_name"])
        setup_page_layout(ws)
        
        # Find department data
        dept_data = next((d for d in dept_summaries if d.get("department") == dept_spec["code"] or d.get("department") == dept_spec["code"].replace("IOT", "IoT")), None)
        if not dept_data:
            dept_data = {"batches": {}} # Fallback to empty if missing
            
        coord = get_coordinator_for_department(dept_spec["code"])
        dept_display_name = "Department of CSE (Internet of Things )" if "IOT" in dept_spec["code"].upper() else ("Department of CSE (Cyber Security)" if "CS" in dept_spec["code"].upper() else f"Department of {dept_spec['code']}")
        
        # Clean White Institutional Header
        header_lines = [
            ("A1:M1", "NANDHA ENGINEERING COLLEGE, ERODE - 638 052.", 12, True),
            ("A2:M2", dept_display_name, 11, True),
            ("A3:M3", f"Date: {report_date}", 11, True),
            ("A4:M4", "Leetcode Performance - Weekly Report", 11, True),
            ("A5:M5", f"Name & Designation of the Academic Coordinator: {coord}", 11, True),
        ]

        for merge_range, text, sz, is_b in header_lines:
            ws.merge_cells(merge_range)
            start_cell = ws[merge_range.split(':')[0]]
            start_cell.value = text
            start_cell.font = Font(name="Times New Roman", size=sz, bold=is_b, color="000000")
            start_cell.alignment = align_center

        ws.row_dimensions[1].height = 24
        ws.row_dimensions[2].height = 20
        ws.row_dimensions[3].height = 20
        ws.row_dimensions[4].height = 22
        ws.row_dimensions[5].height = 22
        
        # Add College Logo (Left)
        logo_path = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(__file__))), "black_white_logo.png")
        if os.path.exists(logo_path):
            img = Image(logo_path)
            img.width = 110
            img.height = 55
            ws.add_image(img, 'A1')

        # Multi-Level Table Header (Rows 6 & 7)
        headers = [
            ("A6", "A7", "Batch"),
            ("B6", "B7", "Number of Students (Total Count)"),
            ("C6", "G6", "Number of Problems Solved"),
            ("H6", "K6", "Weekly Contest Attended: (give the count here)"),
            ("L6", "M6", "Leetcode Contest Rating and Ranking")
        ]
        
        for start, end, val in headers:
            ws.merge_cells(f"{start}:{end}")
            cell = ws[start]
            cell.value = val
            cell.font = font_tbl_head
            cell.alignment = align_center
            
            start_col, start_row = coordinate_to_tuple(start)
            end_col, end_row = coordinate_to_tuple(end)
            for r in range(start_row, end_row + 1):
                for c in range(start_col, end_col + 1):
                    ws.cell(row=r, column=c).border = grid_border
            
        sub_headers = [
            ("C7", "Above 500"), ("D7", "250 - 500"), ("E7", "Less than 250"), ("F7", "Less than 100"), ("G7", "Not yet started"),
            ("H7", "4 Q Solved"), ("I7", "3 Q Solved"), ("J7", "2 Q Solved"), ("K7", "1 Q Solved"),
            ("L7", "Rating: Above 1500"), ("M7", "Ranking: Below 20000")
        ]
        
        for pos, val in sub_headers:
            cell = ws[pos]
            cell.value = val
            cell.font = font_tbl_head
            cell.alignment = align_center
            cell.border = grid_border
            
        ws.row_dimensions[6].height = 32
        ws.row_dimensions[7].height = 32
        
        # Canonical order: IV (2023-2027), III (2024-2028), II (2025-2029)
        required_batches = [
            {"key": "2023_2027", "label": "2023 - 2027", "year": "IV"},
            {"key": "2024_2028", "label": "2024 - 2028", "year": "III"},
            {"key": "2025_2029", "label": "2025 - 2029", "year": "II"}
        ]
        
        current_row = 8
        for b in required_batches:
            batch_key = b["key"]
            batch_label = b["label"]
            
            b_data = dept_data.get("batches", {}).get(batch_key, {})
            last_w = b_data.get("last_week", {})
            curr_w = b_data.get("current_week", {})
            
            tot_students = curr_w.get("total_students", 0) or last_w.get("total_students", 0) or b_data.get("total_students", 0)
            
            # Row 1: Last Week
            r1 = current_row
            ws.row_dimensions[r1].height = 26
            ws.cell(row=r1, column=1, value=f"{batch_label}\n(Last Week)").font = font_bold
            ws.cell(row=r1, column=1).alignment = align_center
            
            # Merged Number of Students cell (B{r1}:B{r1+1})
            ws.merge_cells(f"B{r1}:B{r1+1}")
            cell_b = ws.cell(row=r1, column=2, value=tot_students)
            cell_b.font = font_bold
            cell_b.alignment = align_center
            
            lw_vals = [
                last_w.get("prob_above_500", 0),
                last_w.get("prob_250_500", 0),
                last_w.get("prob_100_249", 0),
                last_w.get("prob_1_99", 0),
                last_w.get("prob_0", 0),
                last_w.get("q4", 0),
                last_w.get("q3", 0),
                last_w.get("q2", 0),
                last_w.get("q1", 0),
                "-",
                "-"
            ]
            for idx_c, v in enumerate(lw_vals, start=3):
                c = ws.cell(row=r1, column=idx_c, value=v)
                c.font = font_regular
                c.alignment = align_center
                
            # Row 2: Current Week
            r2 = current_row + 1
            ws.row_dimensions[r2].height = 26
            ws.cell(row=r2, column=1, value=f"{batch_label}\n(Current Week)").font = font_bold
            ws.cell(row=r2, column=1).alignment = align_center
            
            cw_rating = curr_w.get("rating_above_1500", 0)
            cw_ranking = curr_w.get("rank_below_20000", 0)
            
            cw_vals = [
                curr_w.get("prob_above_500", 0),
                curr_w.get("prob_250_500", 0),
                curr_w.get("prob_100_249", 0),
                curr_w.get("prob_1_99", 0),
                curr_w.get("prob_0", 0),
                curr_w.get("q4", 0),
                curr_w.get("q3", 0),
                curr_w.get("q2", 0),
                curr_w.get("q1", 0),
                cw_rating if cw_rating and cw_rating > 0 else "-",
                cw_ranking if cw_ranking and cw_ranking > 0 else "-"
            ]
            for idx_c, v in enumerate(cw_vals, start=3):
                c = ws.cell(row=r2, column=idx_c, value=v)
                c.font = font_bold if idx_c >= 12 and v != "-" else font_regular
                c.alignment = align_center
                
            current_row += 2

        # Column widths
        widths = {'A': 20, 'B': 18, 'C': 12, 'D': 12, 'E': 13, 'F': 13, 'G': 14, 'H': 11, 'I': 11, 'J': 11, 'K': 11, 'L': 18, 'M': 18}
        for col, width in widths.items():
            ws.column_dimensions[col].width = width

        actual_last_row = current_row - 1
        ws.print_area = f"A1:M{actual_last_row}"
        
        # Apply standard borders to the whole table (Rows 6 to actual_last_row)
        for r in range(6, actual_last_row + 1):
            for c in range(1, 14):
                ws.cell(row=r, column=c).border = grid_border
        
        # Apply standard 'All Borders' to every single cell in the table exactly as requested
        for r in range(5, actual_last_row + 1):
            for c in range(1, 14):
                ws.cell(row=r, column=c).border = grid_border

        # Force clear any stray borders or fills outside the table to prevent unwanted empty cell borders
        no_border = Border()
        for r in range(1, actual_last_row + 20):
            for c in range(14, 20):  # Columns N onwards
                ws.cell(row=r, column=c).border = no_border
        for r in range(actual_last_row + 1, actual_last_row + 20): # Rows below the table
            for c in range(1, 20):
                ws.cell(row=r, column=c).border = no_border

    # Cleanup default sheet
    if "Sheet" in wb.sheetnames:
        wb.remove(wb["Sheet"])
        
    dir_path = os.path.dirname(filepath)
    if dir_path:
        os.makedirs(dir_path, exist_ok=True)
    wb.save(filepath)
    return filepath
